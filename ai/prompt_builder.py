import json


BASE_PROMPT = """
Ты создаёшь профессиональную карточку товара
для российского e-commerce маркетплейса.

ГЛАВНОЕ ПРАВИЛО — СОХРАНЕНИЕ ТОВАРА.

Используй загруженную фотографию как главный
источник истины.

НЕ МЕНЯЙ:

- форму товара;
- пропорции;
- цвет;
- материал;
- логотип;
- реальные детали;
- количество предметов.

Не добавляй характеристики,
которых нет в исходных данных.

ДИЗАЙН:

- современный;
- премиальный;
- чистый;
- коммерческий;
- хорошая визуальная иерархия;
- товар является главным объектом;
- фон не должен конкурировать с товаром.

ТЕКСТ:

Если пользователь указал конкретный текст,
используй его БЕЗ ИЗМЕНЕНИЙ.

Не добавляй случайные слова.

ТИПОГРАФИКА:

Используй крупный легко читаемый заголовок,
контрастный относительно фона.

ПРЕИМУЩЕСТВА:

Используй короткие фразы.
Максимум 3-4 преимущества.

ЭМОДЗИ:

Используй только если они действительно
улучшают восприятие карточки.

Не перегружай изображение.
"""


def build_prompt(
    analysis: dict,
    user_request: str,
    skills: str,
) -> str:

    analysis_json = json.dumps(
        analysis,
        ensure_ascii=False,
        indent=2,
    )

    return f"""
{BASE_PROMPT}

АНАЛИЗ ТОВАРА:

{analysis_json}

ЗАПРОС ПОЛЬЗОВАТЕЛЯ:

{user_request}

ЛОКАЛЬНАЯ БИБЛИОТЕКА ДИЗАЙНА:

{skills}

ЗАДАЧА:

На основе фотографии товара,
анализа, запроса пользователя и
локальных дизайн-правил создай
один максимально подробный
финальный prompt для генерации
карточки товара.

Опиши:

1. композицию;
2. фон;
3. освещение;
4. расположение товара;
5. заголовок;
6. преимущества;
7. типографику;
8. цвета;
9. эмодзи/иконки;
10. глубину резкости;
11. тени;
12. визуальную иерархию.

Не описывай программный код.
Верни только готовый prompt.
"""
