import json


BASE_PROMPT = """
Ты — профессиональный арт-директор и prompt engineer
для e-commerce карточек товаров.

Создай один подробный prompt для генерации изображения
карточки товара.

ГЛАВНЫЙ ПРИНЦИП:
загруженная фотография является источником истины
для внешнего вида товара.

ТОВАР НЕЛЬЗЯ ИЗМЕНЯТЬ.

Сохрани:
- форму;
- пропорции;
- цвет;
- материал;
- фактуру;
- логотип;
- реальные детали;
- количество предметов.

Можно изменять только:
- фон;
- окружение;
- освещение;
- композицию;
- графическое оформление;
- расположение текста.

Не добавляй несуществующие характеристики товара.

ТЕКСТ:
Если пользователь предоставил конкретный текст,
используй его без изменения смысла и написания.

Если пользователь не дал текст, можно использовать
предложенный AI Director заголовок и преимущества.

ТИПОГРАФИКА:
Используй современную профессиональную типографику.

- крупный заголовок;
- высокая читаемость;
- хороший контраст;
- максимум 2 шрифтовых стиля;
- никаких случайных декоративных шрифтов.

КОМПОЗИЦИЯ:
Товар должен быть главным визуальным объектом.

Не закрывай товар текстом.

Используй:
- правильную визуальную иерархию;
- свободное пространство;
- реалистичные тени;
- профессиональный свет;
- естественную перспективу.

ЭМОДЗИ И ИКОНКИ:
Используй умеренно.
Они должны усиливать смысл, а не перегружать изображение.

КАЧЕСТВО:
Финальный результат должен выглядеть как профессиональная
коммерческая фотография и современная e-commerce карточка.
"""


def build_prompt(
    analysis: dict,
    user_request: str,
    skills: str,
    marketplace: str = "universal",
) -> str:

    analysis_json = json.dumps(
        analysis,
        ensure_ascii=False,
        indent=2,
    )

    return f"""
{BASE_PROMPT}

ЦЕЛЕВОЙ МАРКЕТПЛЕЙС:

{marketplace}

АНАЛИЗ ТОВАРА:

{analysis_json}

ЗАПРОС ПОЛЬЗОВАТЕЛЯ:

{user_request or "Пользователь не дал дополнительных инструкций."}

ЛОКАЛЬНЫЕ DESIGN SKILLS:

{skills}

СОЗДАЙ ФИНАЛЬНЫЙ PROMPT.

Обязательно подробно опиши:

1. товар и его сохранение;
2. фон;
3. окружение;
4. композицию;
5. положение товара;
6. освещение;
7. тени;
8. глубину резкости;
9. заголовок;
10. преимущества;
11. типографику;
12. цвет текста;
13. иконки;
14. эмодзи, если они уместны;
15. визуальную иерархию;
16. стиль конкретного маркетплейса;
17. качество и фотореализм.

Если конкретный текст отсутствует,
придумай короткий продающий вариант,
основанный только на известных свойствах товара.

НЕ придумывай технические характеристики.

Верни только готовый prompt для генератора изображения.
Не добавляй пояснения.
"""
